"""SREGym ``before_fault_injection`` hook for the OpsPilot registration (#830).

SREGym imports this module inside its conductor process (``agents.yaml``
``hooks: opspilot_sregym_hooks:HOOKS``, ``sregym/conductor/hooks.py``). It must
therefore be importable on its own: standard library only, and a top-level
name of its own (SREGym's checkout has a top-level ``scripts`` package, so
``scripts.sregym_eval...`` cannot be imported there). The driver copies this
file into the round directory and puts that directory on ``main.py``'s
``PYTHONPATH``.

What it does (R6, 830-U1 = a): in SREGym p12 only, right before the fault is
injected, it creates the harness's read-only Valkey account as Valkey's
``default`` user, through ``kubectl exec -i ... valkey-cli`` with the command
on stdin (the password never reaches an argv). The password is the pass's,
generated by the driver in a mode-600 file in the trial directory; the
result goes to a JSON file next to it, which the agent entry reads. It never
raises: a raise would fail SREGym's whole attempt, and a failed account is
recorded and the pass goes on (#809).
"""

from __future__ import annotations

import json
import os
import subprocess
import types
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

JOB_ENV = "SREGYM_EVAL_JOB"
#: The problem the account is for (same rule as the entry's
#: ``_is_valkey_problem``: seq 12 and this problem).
VALKEY_PROBLEM = "valkey_auth_disruption"
VALKEY_SEQ = 12
VALKEY_DEPLOYMENT = "deploy/valkey-cart"
VALKEY_USER = "opspilot_ro"
#: The documented lab grant of #773; ``agent_entry.VALKEY_GRANT`` is this.
VALKEY_GRANT: tuple[str, ...] = (
    "~*", "resetchannels", "-@all", "+@read", "+info", "+ping", "+hello",
    "+auth", "+select", "+client|setname", "+config|get", "+slowlog|get",
    "+slowlog|len", "+acl|whoami", "+acl|getuser",
)  # fmt: skip
#: Both in the trial's ``work_dir``.
SECRET_FILE = "valkey-readonly.secret"
RESULT_FILE = "valkey-hook-result.json"
EXEC_TIMEOUT_S = 10.0
REPLY_MAX_CHARS = 200


def _reply_text(text: str, password: str) -> str:
    """As ``agent_entry.valkey_reply_text``: password masked, then cut."""
    if password:
        text = text.replace(password, "<redacted>")
    return text.strip()[:REPLY_MAX_CHARS]


def _write_result(work: Path, result: dict[str, Any]) -> None:
    path = work / RESULT_FILE
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        stream.write(json.dumps(result, indent=1) + "\n")


def setuser_line(password: str) -> str:
    return " ".join(
        ["ACL", "SETUSER", VALKEY_USER, "reset", "on", f">{password}", *VALKEY_GRANT]
    )


def exec_argv(kubeconfig: str, namespace: str) -> list[str]:
    return [
        "kubectl", "--kubeconfig", kubeconfig, "-n", namespace,
        "exec", "-i", VALKEY_DEPLOYMENT, "--", "valkey-cli",
    ]  # fmt: skip


def create_account(
    work: Path, kubeconfig: str, namespace: str | None, run: Any = None
) -> dict[str, Any]:
    """Create the account; returns the result record for the caller to write."""
    result: dict[str, Any] = {
        "user": VALKEY_USER,
        "before_fault_injection": True,
        "at": datetime.now(UTC).isoformat(),
        "status": "failed",
        "code": None,
    }
    password = ""
    try:
        password = (work / SECRET_FILE).read_text(encoding="utf-8").strip()
        if not password:
            raise ValueError("empty")
    except (OSError, ValueError, UnicodeDecodeError):
        result["code"] = "SECRET_MISSING"
        return result
    if not namespace:
        result["code"] = "NAMESPACE_MISSING"
        return result
    try:
        done = (run or subprocess.run)(
            exec_argv(kubeconfig, namespace),
            input=setuser_line(password) + "\n",
            capture_output=True,
            text=True,
            timeout=EXEC_TIMEOUT_S,
            check=False,
        )
    except subprocess.TimeoutExpired:
        result["code"] = "EXEC_TIMEOUT"
        return result
    except Exception as error:  # noqa: BLE001 - recorded, never raised
        result["code"] = "EXEC_FAILED:" + type(error).__name__
        return result
    out = (done.stdout or "").strip()
    if done.returncode == 0 and out.splitlines()[:1] == ["OK"]:
        result.update(status="created", code=None)
        return result
    result["code"] = "SETUSER_NOT_OK" if done.returncode == 0 else "EXEC_EXIT_NONZERO"
    result["reply"] = _reply_text(out or (done.stderr or ""), password)
    return result


def before_fault_injection(ctx: Any) -> None:
    try:
        if getattr(ctx, "problem_id", None) != VALKEY_PROBLEM:
            return
        job = json.loads(Path(os.environ[JOB_ENV]).read_text(encoding="utf-8"))
        if job.get("seq") != VALKEY_SEQ:
            return
        work = Path(job["work_dir"])
        result = create_account(
            work, str(job["engineer_kubeconfig"]), getattr(ctx, "namespace", None)
        )
        _write_result(work, result)
    except Exception:  # noqa: BLE001, S110 - never fail SREGym's attempt
        # Nothing else to do: a missing result file is the entry's
        # HOOK_RESULT_MISSING.
        return


#: ``hooks: opspilot_sregym_hooks:HOOKS``; SREGym reads the attribute
#: ``before_fault_injection`` off this object.
HOOKS = types.SimpleNamespace(before_fault_injection=before_fault_injection)
